#!/usr/bin/env python3
"""
ASCII Realm - original music and sound effects, synthesized from scratch.

Run:  python3 build/audio/compose.py   (needs numpy, scipy, ffmpeg)
Writes .ogg files into assets/audio/{music,amb,sfx}.

Everything here is generated by code (no samples), so the audio is original
to this project.
"""
import os, subprocess, tempfile
import numpy as np
from scipy import signal
from scipy.io import wavfile

SR = 44100
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(ROOT, 'assets', 'audio')
rng = np.random.default_rng(7)

# ---------------------------------------------------------------- helpers
def t_axis(dur): return np.arange(int(dur * SR)) / SR
def midi(n): return 440.0 * 2 ** ((n - 69) / 12)
def db(x): return 10 ** (x / 20)

def env_adsr(n, a, d, s, r, sr=SR):
    a, d, r = int(a * sr), int(d * sr), int(r * sr)
    sus = max(0, n - a - d - r)
    e = np.concatenate([np.linspace(0, 1, max(a, 1)), np.linspace(1, s, max(d, 1)), np.full(sus, s), np.linspace(s, 0, max(r, 1))])
    return np.pad(e, (0, max(0, n - len(e))))[:n]

def lp(x, fc, order=2):
    b, a = signal.butter(order, min(fc, SR * 0.45) / (SR / 2), 'low'); return signal.lfilter(b, a, x, axis=0)
def hp(x, fc, order=2):
    b, a = signal.butter(order, fc / (SR / 2), 'high'); return signal.lfilter(b, a, x, axis=0)
def bp(x, lo, hi, order=2):
    b, a = signal.butter(order, [lo / (SR / 2), min(hi, SR * 0.45) / (SR / 2)], 'band'); return signal.lfilter(b, a, x, axis=0)

def saw(freq, t, phase=0.0):
    ph = np.cumsum(np.broadcast_to(freq, t.shape) / SR) + phase
    return 2.0 * (ph - np.floor(ph + 0.5))

def noise(n): return rng.standard_normal(n)
def pink(n):
    w = rng.standard_normal(n)
    b = [0.049922035, -0.095993537, 0.050612699, -0.004408786]
    a = [1, -2.494956002, 2.017265875, -0.522189400]
    return signal.lfilter(b, a, w) * 8
def brown(n):
    x = np.cumsum(rng.standard_normal(n)); x = hp(x, 15); return x / (np.abs(x).max() + 1e-9)

def reverb(x, seconds=3.2, mix=0.35, damp=4000, pre=0.02):
    """Stereo convolution reverb with a synthetic decaying-noise impulse."""
    n = int(seconds * SR)
    tt = np.arange(n) / SR
    out = []
    mono = x if x.ndim == 1 else x.mean(axis=1)
    for ch in range(2):
        ir = rng.standard_normal(n) * np.exp(-tt * 6.9 / seconds)
        ir = lp(ir, damp)
        ir[: int(pre * SR)] = 0
        ir /= np.sqrt(np.sum(ir ** 2)) + 1e-9
        src = x[:, ch] if x.ndim == 2 else mono
        dry = np.pad(src, (0, n))
        wet = signal.fftconvolve(src, ir)
        wet = np.pad(wet, (0, max(0, len(dry) - len(wet))))[: len(dry)]
        out.append(dry * (1 - mix) + wet * mix)
    return np.stack(out, axis=1)

def pan(x, p):  # p: -1 left .. 1 right (equal power)
    a = (p + 1) * np.pi / 4
    return np.stack([x * np.cos(a), x * np.sin(a)], axis=1)

def mix_into(buf, x, start):
    s = int(start * SR)
    if s >= len(buf): return
    e = min(len(buf), s + len(x))
    buf[s:e] += x[: e - s]

def loopify(x, xfade):
    """Make a seamless loop: fold the tail back onto the head with a crossfade."""
    n = int(xfade * SR)
    body, tail = x[:-n].copy(), x[-n:]
    f = np.linspace(0, 1, n)
    if x.ndim == 2: f = f[:, None]
    body[:n] = body[:n] * f + tail * (1 - f)
    return body

def normalize(x, peak_db=-1.0):
    return x / (np.abs(x).max() + 1e-9) * db(peak_db)

def write(path, x, q=5):
    full = os.path.join(OUT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    x = np.clip(x, -1, 1)
    with tempfile.NamedTemporaryFile(suffix='.wav', delete=False) as f: tmp = f.name
    wavfile.write(tmp, SR, (x * 32767).astype(np.int16))
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', tmp, '-c:a', 'libvorbis', '-q:a', str(q), full], check=True)
    os.remove(tmp)
    print(f'  {path:34s} {len(x) / SR:6.1f}s  {os.path.getsize(full) // 1024:5d} KB')

# ---------------------------------------------------------------- instruments
def strings(notes, dur, vel=0.5, bright=1800, attack=0.7, release=1.2):
    t = t_axis(dur + release)
    out = np.zeros(len(t))
    for n in notes:
        f = midi(n)
        for d in (-0.11, -0.04, 0.0, 0.05, 0.12):          # ensemble detune (semitones)
            vib = 1 + 0.0025 * np.sin(2 * np.pi * (4.6 + rng.random()) * t + rng.random() * 6)
            out += saw(f * 2 ** (d / 12) * vib, t, rng.random())
    out = lp(out, bright, 2) / (len(notes) * 5)
    return out * env_adsr(len(t), attack, 0.4, 0.85, release) * vel

def choir(notes, dur, vel=0.4, vowel='ah'):
    formants = {'ah': [(700, 110), (1220, 120), (2600, 160)], 'oo': [(300, 80), (870, 90), (2240, 120)]}[vowel]
    t = t_axis(dur + 2.0)
    src = np.zeros(len(t))
    for n in notes:
        for d in (-0.08, 0.0, 0.07):
            vib = 1 + 0.004 * np.sin(2 * np.pi * (5.0 + rng.random() * 0.6) * t + rng.random() * 6)
            src += saw(midi(n) * 2 ** (d / 12) * vib, t, rng.random())
    out = np.zeros(len(t))
    for fc, bw in formants:
        out += bp(src, fc - bw, fc + bw, 2)
    out = out / (len(notes) * 3) * 3.0
    return out * env_adsr(len(t), 1.4, 0.5, 0.9, 2.0) * vel

def cello(n, dur, vel=0.6, legato_from=None):
    t = t_axis(dur + 0.4)
    f = np.full(len(t), midi(n))
    if legato_from is not None:                         # small portamento between notes
        g = int(0.08 * SR); f[:g] = np.linspace(midi(legato_from), midi(n), g)
    vib_depth = np.clip((t - 0.25) * 2, 0, 1) * 0.004   # vibrato blooms in after the attack
    f = f * (1 + vib_depth * np.sin(2 * np.pi * 5.4 * t))
    x = saw(f, t) * 0.6 + saw(f * 1.003, t, 0.3) * 0.4
    x = lp(x, 2600, 2) + 0.15 * bp(x, 900, 1400)
    return x * env_adsr(len(t), 0.12, 0.2, 0.8, 0.4) * vel

def brass(n, dur, vel=0.5):
    t = t_axis(dur + 0.5)
    e = env_adsr(len(t), 0.18, 0.3, 0.75, 0.5)
    x = saw(midi(n), t) + saw(midi(n) * 1.004, t, 0.4)
    # filter opens with the swell, like a horn
    out = np.zeros(len(t)); seg = 2048
    for i in range(0, len(t), seg):
        fc = 500 + 2600 * e[i]
        out[i:i + seg] = lp(x[i:i + seg], fc, 1)
    return lp(out, 3500) * e * vel * 0.6

def harp(n, vel=0.5, decay=0.9965):
    N = int(SR / midi(n))
    length = int(SR * 3.0)
    exc = np.zeros(length); exc[:N] = lp(rng.uniform(-1, 1, N), 5000)
    a = np.zeros(N + 2); a[0] = 1; a[N] = -decay * 0.5; a[N + 1] = -decay * 0.5
    y = signal.lfilter([1], a, exc)
    return lp(y, 4500) * vel * 0.5

def timpani(n, vel=0.8, length=2.5):
    t = t_axis(length)
    f = midi(n) * (1 + 0.06 * np.exp(-t * 18))
    body = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 2.2)
    over = np.sin(2 * np.pi * np.cumsum(f * 1.5) / SR) * np.exp(-t * 4) * 0.3
    hit = lp(noise(len(t)), 900) * np.exp(-t * 40) * 0.6
    return (body + over + hit) * vel * 0.7

def bell(n, vel=0.4, length=4.0):
    t = t_axis(length)
    out = np.zeros(len(t))
    for ratio, amp, dec in [(1, 1, 1.2), (2.01, 0.5, 1.8), (2.76, 0.4, 2.4), (5.4, 0.25, 4), (8.93, 0.1, 6)]:
        out += np.sin(2 * np.pi * midi(n) * ratio * t) * amp * np.exp(-t * dec)
    return out * vel * 0.3

def drone(n, dur, vel=0.3):
    t = t_axis(dur)
    x = sum(np.sin(2 * np.pi * midi(n) * h * t + rng.random()) / h for h in (1, 2, 3, 4))
    x += 0.4 * saw(midi(n) * 1.002, t)
    x = lp(x, 400)
    swell = 0.75 + 0.25 * np.sin(2 * np.pi * t / 11.0)
    return x * swell * vel

# chords as MIDI note sets (voiced around octave 3-4)
CH = {
    'Dm': [50, 57, 62, 65], 'Bb': [46, 58, 62, 65], 'F': [53, 57, 60, 65], 'C': [48, 55, 60, 64],
    'Gm': [55, 58, 62, 67], 'A': [45, 57, 61, 64], 'Am': [45, 57, 60, 64], 'Em': [52, 55, 59, 64],
    'G': [43, 55, 59, 62],
}
ROOTS = {'Dm': 38, 'Bb': 34, 'F': 41, 'C': 36, 'Gm': 43, 'A': 33, 'Am': 33, 'Em': 40, 'G': 43}

# ---------------------------------------------------------------- title theme
def compose_theme():
    bpm = 64; beat = 60 / bpm; bar = beat * 4
    prog = (['Dm', 'Bb', 'F', 'C'] + ['Dm', 'Bb', 'F', 'C'] + ['Dm', 'Gm', 'A', 'A'] +
            ['Dm', 'Bb', 'F', 'C'] + ['Dm', 'Gm', 'A', 'A'] + ['Dm', 'Bb', 'Gm', 'A'])
    nbars = len(prog)
    total = nbars * bar + 6
    L = np.zeros((int(total * SR), 2))

    for i, ch in enumerate(prog):
        t0 = i * bar
        full = 12 <= i < 20
        mid = 4 <= i < 20
        # strings: always, brighter in the full section
        s = strings(CH[ch], bar, vel=0.42 if full else 0.3, bright=2600 if full else 1500, attack=0.5 if full else 0.9)
        mix_into(L, pan(s, -0.25), t0); mix_into(L, pan(s * 0.8, 0.3), t0 + 0.012)
        # choir in the intro and the climax
        if i < 4 or full:
            c = choir([n + 12 for n in CH[ch][1:]], bar, vel=0.25 if full else 0.2, vowel='ah' if full else 'oo')
            mix_into(L, pan(c, 0.1), t0)
        # drone on the root
        mix_into(L, pan(drone(ROOTS[ch], bar + 0.6, 0.18), 0), t0)
        # harp arpeggios (intro + outro + under the first melody)
        if i < 8 or i >= 20:
            notes = sorted(CH[ch])[1:] + [CH[ch][1] + 12, CH[ch][2] + 12]
            for k in range(8):
                n = notes[[0, 1, 2, 3, 4, 3, 2, 1][k]] + 12
                mix_into(L, pan(harp(n, 0.32), -0.4 + 0.1 * k), t0 + k * beat / 2)
        # cello ostinato under the middle sections
        if mid:
            r = ROOTS[ch] + 12
            for k in range(8):
                nn = r + (0 if k % 4 != 3 else 7)
                mix_into(L, pan(cello(nn, beat * 0.42, 0.22), -0.1), t0 + k * beat / 2)
        # timpani in the climax
        if full:
            mix_into(L, pan(timpani(ROOTS[ch] - 12 + 24, 0.55), 0), t0)
            mix_into(L, pan(timpani(ROOTS[ch] - 12 + 24, 0.32), 0), t0 + beat * 2)
            if i in (15, 19):
                for k in range(4): mix_into(L, pan(timpani(ROOTS[ch] + 12, 0.25 + 0.08 * k), 0), t0 + beat * 3 + k * beat / 4)

    # melody: (bar, beat offset, midi, beats)
    mel1 = [(4, 0, 62, 2), (4, 2, 65, 1), (4, 3, 69, 1), (5, 0, 70, 3), (5, 3, 69, 1), (6, 0, 69, 2), (6, 2, 67, 1), (6, 3, 65, 1), (7, 0, 64, 4),
            (8, 0, 62, 2), (8, 2, 65, 1), (8, 3, 69, 1), (9, 0, 74, 2), (9, 2, 72, 1), (9, 3, 70, 1), (10, 0, 69, 1.5), (10, 1.5, 67, 0.5), (10, 2, 65, 1), (10, 3, 64, 1), (11, 0, 69, 4)]
    mel2 = [(12, 0, 74, 2), (12, 2, 77, 1), (12, 3, 76, 1), (13, 0, 74, 3), (13, 3, 72, 1), (14, 0, 72, 2), (14, 2, 70, 1), (14, 3, 69, 1), (15, 0, 67, 2), (15, 2, 69, 2),
            (16, 0, 74, 2), (16, 2, 77, 1), (16, 3, 81, 1), (17, 0, 79, 2), (17, 2, 77, 1), (17, 3, 76, 1), (18, 0, 77, 1), (18, 1, 76, 1), (18, 2, 74, 1), (18, 3, 73, 1), (19, 0, 74, 4)]
    prev = None
    for b, off, n, ln in mel1:
        x = cello(n - 12, ln * beat * 0.98, 0.55, prev)
        mix_into(L, pan(x, 0.05), b * bar + off * beat); prev = n - 12
    prev = None
    for b, off, n, ln in mel2:
        x = brass(n - 12, ln * beat * 0.95, 0.42)
        y = cello(n, ln * beat * 0.98, 0.32, prev)
        mix_into(L, pan(x, -0.15), b * bar + off * beat)
        mix_into(L, pan(y, 0.2), b * bar + off * beat); prev = n
    # closing bell
    mix_into(L, pan(bell(74, 0.35, 6), 0), (nbars - 1) * bar + beat * 2)

    L = reverb(L, 3.8, 0.38, 3600)
    L = L[: int((nbars * bar + 4.0) * SR)]
    L = loopify(L, 4.0)
    return normalize(L, -1.5)

# ---------------------------------------------------------------- world ambient track
def compose_world():
    # slow, sparse D dorian: long pads, distant choir, occasional harp phrases
    prog = ['Dm', 'C', 'Gm', 'Dm', 'Bb', 'C', 'Dm', 'Am', 'Dm', 'G', 'Bb', 'Dm']
    seg = 12.0
    total = len(prog) * seg + 8
    L = np.zeros((int(total * SR), 2))
    CH2 = dict(CH); CH2['G'] = [43, 55, 59, 62]
    for i, ch in enumerate(prog):
        t0 = i * seg
        s = strings(CH2[ch], seg, vel=0.2, bright=900, attack=3.5, release=4.0)
        mix_into(L, pan(s, -0.35), t0); mix_into(L, pan(s * 0.9, 0.35), t0 + 0.03)
        mix_into(L, pan(drone(ROOTS.get(ch, 38), seg + 4, 0.12), 0), t0)
        if i % 3 == 1:
            c = choir([n + 12 for n in CH2[ch][1:3]], seg * 0.8, vel=0.12, vowel='oo')
            mix_into(L, pan(c, 0.2), t0 + 2)
        if i % 2 == 0:  # a short harp phrase drifting down
            notes = sorted(CH2[ch])[1:] + [CH2[ch][1] + 12]
            phrase = [3, 2, 1, 2, 0] if i % 4 == 0 else [0, 2, 3, 1]
            for k, idx in enumerate(phrase):
                mix_into(L, pan(harp(notes[idx] + 12, 0.22, 0.9975), 0.5 - 0.2 * k), t0 + 3 + k * 0.62 + rng.random() * 0.08)
        if i in (5, 10):
            mix_into(L, pan(bell(81 if i == 5 else 74, 0.12, 7), -0.3), t0 + 6)
    L = reverb(L, 5.0, 0.5, 2800)
    L = L[: int((len(prog) * seg + 6) * SR)]
    L = loopify(L, 6.0)
    return normalize(L, -4.0)

# ---------------------------------------------------------------- ambience loops
def amb_rain(dur=24.0):
    n = int((dur + 2) * SR)
    L = np.zeros((n, 2))
    for ch in range(2):
        hiss = bp(pink(n), 500, 9000) * 0.5 + lp(brown(n), 300) * 0.4
        drops = np.zeros(n)
        idx = rng.integers(0, n - 2000, size=int(dur * 380))
        for i in idx:
            k = int(SR * rng.uniform(0.002, 0.008))
            drops[i:i + k] += rng.uniform(0.1, 0.6) * np.exp(-np.arange(k) / (k / 4)) * rng.choice([-1, 1])
        drops = bp(drops, 1500, 8000)
        L[:, ch] = hiss * 0.6 + drops * 0.9
    return normalize(loopify(L, 2.0), -3)

def amb_wind(dur=30.0):
    n = int((dur + 3) * SR)
    t = np.arange(n) / SR
    L = np.zeros((n, 2))
    for ch in range(2):
        src = pink(n)
        out = np.zeros(n); blk = 4096
        for i in range(0, n, blk):
            fc = 380 + 260 * np.sin(2 * np.pi * (t[i] / 9.0 + ch * 0.3)) + 120 * np.sin(2 * np.pi * t[i] / 3.7)
            out[i:i + blk] = bp(src[i:i + blk], fc * 0.6, fc * 1.6, 1)
        gust = 0.45 + 0.55 * (0.5 + 0.5 * np.sin(2 * np.pi * t / 7.3 + ch)) * (0.6 + 0.4 * np.sin(2 * np.pi * t / 2.9))
        L[:, ch] = lp(out * gust, 2500)
    return normalize(loopify(L, 3.0), -5)

def amb_night(dur=20.0):
    # crickets: pulsed high chirps at a few pitches, plus a soft low bed
    n = int((dur + 2) * SR)
    t = np.arange(n) / SR
    L = np.zeros((n, 2))
    for c in range(6):
        f = rng.uniform(4200, 5400); rate = rng.uniform(2.2, 3.4); p = rng.uniform(-0.8, 0.8)
        trill = (np.sin(2 * np.pi * 32 * t) > 0.2) * (np.sin(2 * np.pi * rate * t + rng.random() * 6) > 0.55)
        trill = lp(trill.astype(float), 200)
        x = np.sin(2 * np.pi * f * t) * trill * rng.uniform(0.15, 0.35)
        L += pan(x, p)
    L += pan(lp(pink(n), 250) * 0.05, 0)
    return normalize(loopify(L, 2.0), -8)

def amb_day(dur=24.0):
    # sparse birdsong: little FM chirps and whistles
    n = int((dur + 2) * SR)
    L = np.zeros((n, 2))
    for _ in range(int(dur * 1.2)):
        s = rng.uniform(0, dur)
        kind = rng.integers(0, 3)
        notes = rng.integers(2, 6)
        p = rng.uniform(-0.9, 0.9)
        for k in range(notes):
            d = rng.uniform(0.05, 0.14); tt = t_axis(d)
            f0 = rng.uniform(2400, 4200)
            sweep = f0 * (1 + (0.4 if kind == 0 else -0.3) * tt / d) * (1 + 0.05 * np.sin(2 * np.pi * 60 * tt))
            x = np.sin(2 * np.pi * np.cumsum(sweep) / SR) * np.sin(np.pi * tt / d) ** 2 * rng.uniform(0.1, 0.3)
            mix_into(L, pan(x, p), s + k * (d + rng.uniform(0.02, 0.08)))
    L += pan(lp(pink(n), 400) * 0.03, 0)
    L = reverb(L, 1.2, 0.2, 6000)[:n]
    return normalize(loopify(L, 2.0), -9)

def amb_fire(dur=8.0):
    n = int((dur + 1) * SR)
    roar = lp(brown(n), 260) * 0.5
    crack = np.zeros(n)
    for i in rng.integers(0, n - 3000, size=int(dur * 22)):
        k = int(SR * rng.uniform(0.001, 0.012))
        crack[i:i + k] += rng.uniform(0.2, 1.0) * np.exp(-np.arange(k) / (k / 5)) * noise(k)
    crack = hp(crack, 1200)
    x = roar + crack * 0.8
    return normalize(loopify(np.stack([x, x * 0.95], 1), 1.0), -4)

# ---------------------------------------------------------------- one-shot effects
def sfx_step(surface):
    d = 0.16; n = int(d * SR); t = np.arange(n) / SR
    if surface == 'grass':
        x = bp(noise(n), 700, 4200) * np.exp(-t * 28)
        rustle = bp(noise(n), 2500, 7000) * np.exp(-t * 14) * 0.5
        thud = lp(noise(n), 160) * np.exp(-t * 40) * 1.5
        x = x + rustle + thud
    else:
        x = bp(noise(n), 1200, 5000) * np.exp(-t * 70) + lp(noise(n), 220) * np.exp(-t * 35) * 2.0
        x += np.sin(2 * np.pi * rng.uniform(180, 240) * t) * np.exp(-t * 45) * 0.4
    return normalize(x, -3)

def sfx_swing(heavy=False):
    d = 0.5 if heavy else 0.32; n = int(d * SR); t = np.arange(n) / SR
    src = noise(n)
    out = np.zeros(n); blk = 512
    f0, f1 = (260, 1300) if heavy else (550, 2600)
    for i in range(0, n, blk):
        u = i / n
        fc = f0 + (f1 - f0) * np.sin(np.pi * min(1, u * 1.2)) ** 1.5
        out[i:i + blk] = bp(src[i:i + blk], fc * 0.7, fc * 1.4, 1)
    e = np.sin(np.pi * np.clip(t / d, 0, 1)) ** (1.6 if heavy else 2.2)
    return normalize(out * e, -4)

def sfx_hit_bone():
    d = 0.5; n = int(d * SR); t = np.arange(n) / SR
    crack = hp(noise(n), 2500) * np.exp(-t * 90)
    knock = bp(noise(n), rng.uniform(450, 700), rng.uniform(900, 1300), 2) * np.exp(-t * 22) * 3
    thump = lp(noise(n), 180) * np.exp(-t * 30) * 2.5
    rattle = np.zeros(n)
    for k in range(5):
        s = int(SR * (0.03 + k * rng.uniform(0.02, 0.05)))
        m = int(SR * 0.006)
        if s + m < n: rattle[s:s + m] += bp(noise(m), 2500, 6000) * rng.uniform(0.2, 0.6)
    return normalize(crack + knock + thump + rattle, -1.5)

def sfx_hit_player():
    d = 0.45; n = int(d * SR); t = np.arange(n) / SR
    thud = lp(noise(n), 260) * np.exp(-t * 16) * 3
    slash = bp(noise(n), 1500, 5000) * np.exp(-t * 35)
    grunt = np.sin(2 * np.pi * np.cumsum(140 * (1 - 0.3 * t / d)) / SR) * np.exp(-t * 9) * 0.5
    grunt = lp(grunt + 0.3 * saw(130 * (1 - 0.3 * t / d), t) * np.exp(-t * 9), 900)
    return normalize(thud + slash + grunt, -1.5)

def sfx_clang():
    d = 1.2; n = int(d * SR); t = np.arange(n) / SR
    x = sum(np.sin(2 * np.pi * f * t) * a * np.exp(-t * dc) for f, a, dc in [(523, 1, 4), (1312, 0.7, 6), (2213, 0.5, 8), (3170, 0.35, 11), (4410, 0.2, 14)])
    x += hp(noise(n), 3000) * np.exp(-t * 60) * 0.8
    return normalize(x, -3)

def sfx_dodge():
    d = 0.6; n = int(d * SR); t = np.arange(n) / SR
    whoosh = bp(noise(n), 300, 1400) * np.sin(np.pi * np.clip(t / 0.35, 0, 1)) ** 2
    land = np.zeros(n); s = int(0.36 * SR)
    m = n - s; tt = np.arange(m) / SR
    land[s:] = lp(noise(m), 200) * np.exp(-tt * 25) * 2.2 + bp(noise(m), 800, 3000) * np.exp(-tt * 30) * 0.6
    return normalize(whoosh + land, -3)

def sfx_rattle(length=0.8, density=26):
    n = int(length * SR); x = np.zeros(n)
    for _ in range(int(length * density)):
        s = rng.integers(0, n - 600); m = int(SR * rng.uniform(0.003, 0.009))
        f = rng.uniform(1800, 4200); tt = np.arange(m) / SR
        x[s:s + m] += np.sin(2 * np.pi * f * tt) * np.exp(-tt * 600) * rng.uniform(0.3, 1)
    return normalize(bp(x, 1200, 7000), -4)

def sfx_skel_awake():
    d = 2.4; n = int(d * SR); t = np.arange(n) / SR
    groan_src = saw(70 + 15 * np.sin(2 * np.pi * 0.7 * t), t) + 0.5 * noise(n)
    groan = bp(groan_src, 120, 600) * np.sin(np.pi * np.clip(t / d, 0, 1)) * 0.6
    r = np.zeros(n); rr = sfx_rattle(1.6, 40); r[int(0.4 * SR):int(0.4 * SR) + len(rr)] = rr[: n - int(0.4 * SR)]
    return normalize(groan + r * 0.8, -3)

def sfx_skel_death():
    d = 1.6; n = int(d * SR); x = np.zeros(n)
    for k in range(40):
        s = int(SR * (abs(rng.normal(0.35, 0.25)))); m = int(SR * rng.uniform(0.004, 0.02))
        if s + m >= n: continue
        tt = np.arange(m) / SR
        x[s:s + m] += bp(noise(m), rng.uniform(900, 2000), rng.uniform(3000, 6000)) * np.exp(-tt * 200) * rng.uniform(0.3, 1)
    t = np.arange(n) / SR
    thud = lp(noise(n), 160) * np.exp(-np.clip(t - 0.5, 0, None) * 18) * (t > 0.5) * 2.0
    return normalize(x + thud, -2)

def sfx_flask():
    d = 1.4; n = int(d * SR); t = np.arange(n) / SR; x = np.zeros(n)
    for s in (0.25, 0.55, 0.82):
        m = int(0.18 * SR); tt = np.arange(m) / SR
        g = np.sin(2 * np.pi * np.cumsum(220 * (1 - 0.5 * tt / 0.18)) / SR) * np.exp(-tt * 18)
        g = lp(g + 0.4 * lp(noise(m), 500) * np.exp(-tt * 25), 900)
        mix_into(x, g, s)
    for k, f in enumerate([1175, 1480, 1760, 2349]):
        tt = t_axis(0.8)
        mix_into(x, np.sin(2 * np.pi * f * tt) * np.exp(-tt * 5) * 0.12, 1.0 + k * 0.07)
    return normalize(x, -3)

def sfx_rest():
    d = 5.0; L = np.zeros((int(d * SR), 2))
    for k, n in enumerate([62, 66, 69, 74, 78]):
        mix_into(L, pan(bell(n, 0.35, 4.5), -0.4 + 0.2 * k), k * 0.12)
    sw = choir([74, 78, 81], 2.5, 0.25, 'oo')
    mix_into(L, pan(sw, 0), 0.1)
    return normalize(reverb(L, 3.5, 0.45)[: len(L)], -2)

def sfx_died():
    d = 5.0; n = int(d * SR); t = np.arange(n) / SR
    boom = lp(brown(n), 90) * np.exp(-t * 1.2) * 1.5 + np.sin(2 * np.pi * 41 * t) * np.exp(-t * 1.5)
    swell = strings([38, 45, 50, 51], 3.5, vel=0.5, bright=700, attack=1.5, release=1.0)
    L = pan(boom * 0.7, 0)
    mix_into(L, pan(swell, 0), 0.2)
    return normalize(reverb(L, 4.0, 0.4)[: n], -1.5)

def sfx_runes():
    L = np.zeros((int(1.6 * SR), 2))
    for k, n in enumerate([81, 85, 88, 93]):
        mix_into(L, pan(bell(n, 0.25, 1.4), -0.3 + 0.2 * k), k * 0.06)
    return normalize(reverb(L, 1.5, 0.3)[: len(L)], -4)

def sfx_ui(kind):
    if kind == 'move':
        tt = t_axis(0.05); x = np.sin(2 * np.pi * 1900 * tt) * np.exp(-tt * 90) * 0.5
    elif kind == 'select':
        x = np.zeros(int(0.25 * SR))
        for k, f in enumerate([880, 1320]):
            tt = t_axis(0.18); mix_into(x, np.sin(2 * np.pi * f * tt) * np.exp(-tt * 22) * 0.5, k * 0.06)
    elif kind == 'open':
        tt = t_axis(0.25); x = bp(noise(len(tt)), 800, 3000) * np.sin(np.pi * tt / 0.25) * 0.4
        x += np.sin(2 * np.pi * 660 * tt) * np.exp(-tt * 20) * 0.3
    else:  # back / close
        x = np.zeros(int(0.22 * SR))
        for k, f in enumerate([1320, 880]):
            tt = t_axis(0.15); mix_into(x, np.sin(2 * np.pi * f * tt) * np.exp(-tt * 25) * 0.4, k * 0.05)
    return normalize(x, -6)

def sfx_torch():
    d = 0.8; n = int(d * SR); t = np.arange(n) / SR
    whoosh = bp(noise(n), 250, 1600) * np.sin(np.pi * np.clip(t / 0.4, 0, 1)) ** 2
    crack = np.zeros(n)
    for i in rng.integers(int(0.15 * SR), n - 500, size=14):
        k = int(SR * 0.004); crack[i:i + k] += noise(k) * np.exp(-np.arange(k) / 40)
    return normalize(whoosh + hp(crack, 1500) * 0.7, -4)

def sfx_burn():
    d = 2.0; n = int(d * SR); t = np.arange(n) / SR
    crack = np.zeros(n)
    for i in rng.integers(0, n - 800, size=70):
        k = int(SR * rng.uniform(0.001, 0.006)); crack[i:i + k] += noise(k) * np.exp(-np.arange(k) / 30) * rng.uniform(0.3, 1)
    sizzle = bp(noise(n), 3000, 9000) * 0.15
    e = np.minimum(1, t * 6) * np.exp(-t * 1.4)
    return normalize((hp(crack, 1500) + sizzle) * e, -5)

def sfx_tear():
    d = 0.5; n = int(d * SR); t = np.arange(n) / SR
    x = bp(noise(n), 2500, 8000) * np.exp(-t * 9) * (0.6 + 0.4 * np.sin(2 * np.pi * 60 * t))
    return normalize(x, -10)

def sfx_thunder(close):
    d = 8.0; n = int(d * SR); t = np.arange(n) / SR
    rumble = lp(brown(n), 130 if close else 90)
    bumps = np.zeros(n)
    for _ in range(9):
        c = rng.uniform(0.2, 4.5); w = rng.uniform(0.2, 0.9)
        bumps += np.exp(-((t - c) / w) ** 2) * rng.uniform(0.4, 1)
    env = (1 - np.exp(-t * 6)) * np.exp(-t * (0.45 if close else 0.35))
    x = rumble * (0.35 + bumps) * env
    if close:
        crack = hp(noise(n), 900) * np.exp(-t * 12) * 1.2 + bp(noise(n), 200, 2000) * np.exp(-t * 4) * 0.6
        x = x + crack
    L = np.stack([x, np.roll(x, int(0.012 * SR))], 1)
    return normalize(reverb(L, 3.0, 0.3, 1800)[:n], -1.5)

